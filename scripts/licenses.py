#!/usr/bin/env python3
"""Writes ClasifyCore/Sources/ClasifyCore/Licenses.swift from LibrespotBridge/Cargo.lock (card BF, change 213).

It lists every Rust crate that the macOS build links, by license: a crate goes under each license
of its license expression that Clasify uses. The license texts are in scripts/licenses/.
Run it after a Cargo.lock change. With --check it only says if the Swift file is out of date.
"""
import json, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "ClasifyCore/Sources/ClasifyCore/Licenses.swift")
# A line is at most 264 pt of 11 pt Helvetica, with 8% to spare for Helvetica Neue: the text box of the
# license screen (PocketLicense).
WIDTH = 264 / 11 * 1000 * 0.92
# Helvetica advance widths, in 1/1000 em (from its AFM), for the characters that differ from the default.
NARROW = {**dict.fromkeys(" !,./:;[]ftI", 278), **dict.fromkeys("ijl|'", 222), "r": 333, "(": 333, ")": 333,
          "-": 333, '"': 355, "m": 833, "w": 722, "M": 833, "W": 944, "@": 1015, "©": 737}


def advance(s):
    return sum(NARROW.get(c, 556 if c.islower() or c.isdigit() else 667 if c.isupper() else 584) for c in s)


def fill(words):
    """Greedy wrap of the words to WIDTH."""
    lines, line = [], ""
    for w in words.split():
        if line and advance(line + " " + w) > WIDTH:
            lines.append(line)
            line = w
        else:
            line = f"{line} {w}" if line else w
    return lines + [line] if line else lines
LICENSES = [  # (SPDX ID, row name), in row order
    ("MIT", "MIT License"), ("Apache-2.0", "Apache License 2.0"), ("Unicode-3.0", "Unicode License"),
    ("Zlib", "Zlib License"), ("BSD-3-Clause", "BSD License"), ("MPL-2.0", "Mozilla Public License 2.0"),
]


def crates():
    """The crates of the macOS build (both targets of scripts/build-bridge.sh), normal and build
    dependencies only, without our own."""
    found = {}
    for target in ("aarch64-apple-darwin", "x86_64-apple-darwin"):
        meta = json.loads(subprocess.check_output(
            ["cargo", "metadata", "--locked", "--format-version", "1", "--filter-platform", target],
            cwd=os.path.join(ROOT, "LibrespotBridge")))
        packages = {p["id"]: p for p in meta["packages"]}
        nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
        root = meta["resolve"]["root"]
        seen, todo = set(), [root]
        while todo:
            i = todo.pop()
            if i not in seen:
                seen.add(i)
                todo += [d["pkg"] for d in nodes[i]["deps"] if any(k["kind"] in (None, "build") for k in d["dep_kinds"])]
        found.update({i: packages[i] for i in seen if i != root})
    return list(found.values())


def wrap(text):
    """Each paragraph wrapped to WIDTH, with one empty line between. Copyright lines (they name one
    crate's authors), ===/--- underlines and the * frame of the MPL's boxes are left out."""
    lines = []
    text = re.sub(r"(?m)^[\s*]*[=\-]{3,}[\s*]*$", "", text)  # an underline ends its heading's paragraph
    for para in re.split(r"\n\s*\n", text.strip()):
        lines_in = [re.sub(r"^\*|\*$", "", l.strip()).strip() for l in para.splitlines()]
        words = " ".join(l for l in lines_in if not l.startswith("Copyright") and not re.fullmatch(r"[=\-*]*", l))
        if words:
            lines += fill(words) + [""]
    return lines


def swift():
    parts = {spdx: set() for spdx, _ in LICENSES}
    for p in crates():
        ids = set(re.split(r"\s+(?:OR|AND|WITH)\s+|\s*/\s*", re.sub(r"[()]", "", p.get("license") or "")))
        used = [spdx for spdx, _ in LICENSES if spdx in ids]
        if not used:
            sys.exit(f"{p['name']} {p['version']}: license {p.get('license')!r} is not in scripts/licenses.py")
        for spdx in used:
            parts[spdx].add(p["name"])
    out = ["// Generated by scripts/licenses.py from LibrespotBridge/Cargo.lock. Do not edit.", "",
           "extension License {", "    /// One row a license, in the Licenses list (card BF, change 213).",
           "    public static let all: [License] = ["]
    for spdx, name in LICENSES:
        text = open(os.path.join(ROOT, "scripts/licenses", spdx + ".txt"), encoding="utf-8").read()
        lines = wrap(text) + fill(", ".join(sorted(parts[spdx])))
        out.append(f'        License(name: "{name}", lines: [')
        out += [f'            #"{l}"#,' for l in lines]
        out.append("        ]),")
    out += ["    ]", "}", ""]
    return "\n".join(out)


if __name__ == "__main__":
    new = swift()
    if "--check" in sys.argv:
        if open(OUT, encoding="utf-8").read() != new:
            sys.exit("Licenses.swift is out of date: run scripts/licenses.py")
    else:
        open(OUT, "w", encoding="utf-8").write(new)
